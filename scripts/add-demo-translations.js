async function addTranslations() {
  console.log('Adding Hindi and Punjabi translations to songs...\n')

  for (const [slug, data] of Object.entries(translations)) {
    try {
      const result = await prisma.song.update({
        where: { slug },
        data: {
          lyricsHindi: data.lyricsHindi,
          lyricsPunjabi: data.lyricsPunjabi
        }
      })
      console.log(`Updated: ${result.title}`)
    } catch (error) {
      console.log(`Song not found or error: ${slug}`)
    }
  }

  console.log('\nDone!')
}

addTranslations()
  .catch(console.error)
  .finally(() => prisma.$disconnect())
